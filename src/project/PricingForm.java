    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String details = spnProfit.getValue().toString();
        int response = JOptionPane.showConfirmDialog(rootPane, "Are you sure");
        if(response == JOptionPane.NO_OPTION || response == JOptionPane.CLOSED_OPTION){
            return;
        }
        try {
            new Utils().emptyFile("pricing.txt");
        } catch (IOException ex) {
            Logger.getLogger(PricingForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        new Utils().writeToFile("pricing.txt", details);
        JOptionPane.showMessageDialog(rootPane, "Details Saved");
    }//GEN-LAST:event_jButton1ActionPerformed

